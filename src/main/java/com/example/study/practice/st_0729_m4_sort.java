    public static void main(String[] args) {
        System.out.println("===== mergeIntervals (정렬) =====");
        check(new int[][] { { 1, 3 }, { 2, 6 }, { 8, 10 }, { 15, 18 } },
                new int[][] { { 1, 6 }, { 8, 10 }, { 15, 18 } });
        check(new int[][] { { 1, 4 }, { 4, 5 } }, new int[][] { { 1, 5 } });
        check(new int[][] { { 1, 4 }, { 2, 3 } }, new int[][] { { 1, 4 } });
        check(new int[][] { { 1, 4 }, { 5, 6 } }, new int[][] { { 1, 4 }, { 5, 6 } });
        check(new int[][] { { 2, 3 }, { 1, 10 }, { 4, 5 } }, new int[][] { { 1, 10 } });
        check(new int[][] { { 1, 1 } }, new int[][] { { 1, 1 } });
        check(new int[][] { { 5, 6 }, { 1, 2 }, { 3, 4 } },
                new int[][] { { 1, 2 }, { 3, 4 }, { 5, 6 } });
    }

    static void check(int[][] input, int[][] expected) {
        String before = arr2DToStr(input);
        int[][] actual = mergeIntervals(input);
        boolean ok = actual != null && arr2DToStr(actual).equals(arr2DToStr(expected));
        System.out.printf("%s %s -> 기대:%s 결과:%s%n",
                ok ? "[통과]" : "[실패]", before,
                arr2DToStr(expected), actual == null ? "null" : arr2DToStr(actual));
    }

    static String arr2DToStr(int[][] arr) {
        StringBuilder sb = new StringBuilder("[");
        for (int i = 0; i < arr.length; i++) {
            sb.append(i == 0 ? "" : " ").append("[");
            for (int j = 0; j < arr[i].length; j++) {
                sb.append(j == 0 ? "" : ",").append(arr[i][j]);
            }
            sb.append("]");
        }
        return sb.append("]").toString();
    }
