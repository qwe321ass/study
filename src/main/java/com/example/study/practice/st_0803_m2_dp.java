package com.example.study.practice;

/*
 * ============================================================
 *  1로 만들기   [유형: Dynamic Programming]   (난이도: Medium)
 * ============================================================
 *
 * 정수 N이 주어졌을 때, 아래 3가지 연산을 적절히 사용해서 1을 만드는 연산 횟수의 최솟값을 구하세요.
 *
 * 1. X가 3으로 나누어 떨어지면, 3으로 나눈다.
 * 2. X가 2로 나누어 떨어지면, 2로 나눈다.
 * 3. 1을 뺀다.
 *
 * 예) N = 2   -> 1 (2 -> 1, 1회)
 * 예) N = 10  -> 3 (10 -> 9 -> 3 -> 1, 3회)
 *
 * ------------------------------------------------------------
 * [이 유형의 핵심 개념]
 *
 * 단순하게 "3으로 나누는 게 제일 빠르게 줄어드니 3으로 먼저 나누자"라고 생각하는 그리디 방식은 오답입니다.
 * 예: 10의 경우, (10 -> 5 -> 4 -> 2 -> 1: 4회) 보다 (10 -> 9 -> 3 -> 1: 3회)가 더 적습니다.
 *
 * 따라서 모든 가능성 중 최솟값을 기록하는 동적 계획법(DP)을 사용해야 합니다.
 *
 * - DP 배열 정의:
 *   dp[i] = 숫자 i를 1로 만드는 최소 연산 횟수
 *
 * - 점화식 (i를 만드는 3가지 방법 중 최솟값 + 1):
 *    기본적으로 1을 빼는 경우: dp[i] = dp[i - 1] + 1
 *    만약 i가 2로 나누어 떨어지면: dp[i] = Math.min(dp[i], dp[i / 2] + 1)
 *    만약 i가 3으로 나누어 떨어지면: dp[i] = Math.min(dp[i], dp[i / 3] + 1)
 *
 * ------------------------------------------------------------
 * [힌트]
 *
 * - dp[1] = 0 (1은 이미 1이므로 0회)
 * - for (int i = 2; i <= N; i++) 루프를 돌면서 dp 테이블을 채워나갑니다.
 *
 * ------------------------------------------------------------
 * [자주 하는 실수]
 *
 * - if-else if 구문 사용:
 *   2로 나누어 떨어지고 3으로도 나누어 떨어지는 수(예: 6) 또는 1을 빼는 선택이 더 유리한 경우가 있으므로,
 *   else if로 건너뛰면 안 되고 3가지 경우의 Math.min을 모두 비교해야 합니다.
 */
public class st_0803_m2_dp {

    public static int makeOne(int n) {

        // dp 배열 생성
        int[] dp = new int[n + 1];

        // 2부터 n까지 반복
        for (int i = 2; i <= n; i++) {
            // 일단 1을 빼는 경우로 초기화
            dp[i] = dp[i - 1] + 1;

            // 2로 나누어 떨어지는 경우, 더 작은 값으로 갱신
            if (i % 2 == 0) {
                dp[i] = Math.min(dp[i], dp[i / 2] + 1);
            }
            // 3으로 나누어 떨어지는 경우, 더 작은 값으로 갱신
            if (i % 3 == 0) {
                dp[i] = Math.min(dp[i], dp[i / 3] + 1);
            }
        }
        // n을 1로 만드는 최소 연산 횟수 반환
        return dp[n];
    }

    // =========================================================
    // ↓↓↓ 아래는 채점용입니다. 건드리지 않아도 됩니다. ↓↓↓
    // =========================================================

    public static void main(String[] args) {
        System.out.println("===== makeOne (Dynamic Programming) =====");

        check(2, 1);
        check(10, 3);
        check(6, 2); // 6 -> 3 -> 1 (2회) 또는 6 -> 2 -> 1 (2회)
        check(1, 0);
        check(12, 3); // 12 -> 4 -> 2 -> 1 (3회)
    }

    static void check(int n, int expected) {
        int actual = makeOne(n);
        if (actual == expected) {
            System.out.println("✅ [PASS] N=" + n + " => 결과: " + actual);
        } else {
            System.out.println("❌ [FAIL] N=" + n + " => 예상값: " + expected + ", 실제값: " + actual);
        }
    }
}
